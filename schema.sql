BEGIN;

-- --------------------------------------------------
-- REGISTERED DATA SOURCES
-- --------------------------------------------------

CREATE TABLE IF NOT EXISTS targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_name TEXT NOT NULL UNIQUE,
    api_endpoint TEXT NOT NULL,
    extraction_method TEXT NOT NULL
        CHECK (
            extraction_method IN ('httpx', 'playwright', 'websocket')
        ),
    tier INTEGER NOT NULL DEFAULT 1
        CHECK (tier IN (1, 2)),
    consecutive_empty_polls INTEGER NOT NULL DEFAULT 0
        CHECK (consecutive_empty_polls >= 0),
    consecutive_failures INTEGER NOT NULL DEFAULT 0
        CHECK (consecutive_failures >= 0),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    last_checked TIMESTAMPTZ,
    cooldown_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS targets_priority_idx
ON targets (is_active, tier, consecutive_failures);


-- --------------------------------------------------
-- TASK QUEUE
-- --------------------------------------------------

CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id TEXT NOT NULL UNIQUE,
    source_target_id BIGINT REFERENCES targets(id)
        ON DELETE SET NULL,
    source_platform TEXT NOT NULL,
    category TEXT NOT NULL,
    payload TEXT NOT NULL,

    payout_usd NUMERIC(14, 6) NOT NULL
        CHECK (payout_usd >= 0),

    est_seconds INTEGER NOT NULL
        CHECK (est_seconds > 0),

    -- Expected payout per estimated second.
    -- This is not guaranteed profit or ROI.
    roc_score DOUBLE PRECISION GENERATED ALWAYS AS
        (payout_usd::DOUBLE PRECISION / est_seconds) STORED,

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN ('pending', 'processing', 'completed', 'failed')
        ),

    attempts INTEGER NOT NULL DEFAULT 0
        CHECK (attempts >= 0),

    max_attempts INTEGER NOT NULL DEFAULT 3
        CHECK (max_attempts > 0),

    available_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    locked_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,

    CHECK (attempts <= max_attempts)
);

CREATE INDEX IF NOT EXISTS tasks_roc_idx
ON tasks (status, roc_score DESC, created_at ASC);

CREATE INDEX IF NOT EXISTS tasks_recovery_idx
ON tasks (status, locked_at);

CREATE INDEX IF NOT EXISTS tasks_available_idx
ON tasks (available_at)
WHERE status = 'pending';


-- --------------------------------------------------
-- AUDIT HISTORY
-- --------------------------------------------------

CREATE TABLE IF NOT EXISTS task_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id)
        ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS task_events_task_idx
ON task_events (task_id, created_at);


